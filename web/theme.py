"""Shared Women Count colors for the website, Streamlit, and Plotly.

Edit BRAND_COLORS to update the brand palette. Run `python theme.py` from
the web directory to regenerate the website's CSS, then commit both files.
When copied elsewhere, import this module to reuse the colors and helpers.
"""

from pathlib import Path


# Edit the four brand colors here.
BRAND_COLORS = {
    "gold": "#e7b70d",
    "teal": "#52abb4",
    "near-black": "#161616",
    "white": "#ffffff",
}

GOLD = BRAND_COLORS["gold"]
TEAL = BRAND_COLORS["teal"]
NEAR_BLACK = BRAND_COLORS["near-black"]
WHITE = BRAND_COLORS["white"]

# Roles used by Streamlit sections, custom HTML, and Plotly.
PRIMARY = GOLD
TEXT = NEAR_BLACK
BACKGROUND = WHITE
SURFACE = "#f7f7f7"
LINK = "#917204"
BORDER = "#e2e2e2"
SERIES = ["#a6830a", "#2a78d6", "#b8336a", "#1baf7a", "#6250d6"]
SEQUENTIAL = None
MUTED = "#5e5e5e"
NO_DATA = "#b8b8b8"
FONT = "Cantarell, Arial, sans-serif"
HEADING_FONT = "'Work Sans', Arial, sans-serif"


def plotly_layout() -> dict:
    """Shared look for Plotly charts:  fig.update_layout(**theme.plotly_layout())"""
    return dict(
        font=dict(family=FONT, color=TEXT, size=12),
        colorway=SERIES,
        paper_bgcolor=BACKGROUND,
        plot_bgcolor=BACKGROUND,
        margin=dict(l=40, r=10, t=40, b=30),
    )


def placeholder(label: str, note: str = "", height: int = 160) -> None:
    """A bordered box marking where a real element will go."""
    import streamlit as st

    with st.container(border=True, height=height):
        st.markdown(f"**{label}**")
        if note:
            st.caption(note)


def _css_block(variables: dict[str, str]) -> str:
    declarations = "\n".join(f"  --{name}: {value};" for name, value in variables.items())
    return ":root {\n" + declarations + "\n}\n"


def css_variables() -> str:
    """Expose brand colors and existing role names for custom HTML."""
    return _css_block({
        **BRAND_COLORS,
        "primary": "var(--gold)",
        "text": "var(--near-black)",
        "bg": "var(--white)",
        "surface": SURFACE,
        "link": LINK,
        "border": BORDER,
        "muted": MUTED,
        "no-data": NO_DATA,
        "font": FONT,
    })


if __name__ == "__main__":
    destination = Path(__file__).resolve().parent / "src" / "palette.css"
    destination.write_text(
        "/* Generated by web/theme.py. Edit BRAND_COLORS and run npm run prepare:palette in web/. */\n"
        + _css_block(BRAND_COLORS),
        encoding="utf-8",
        newline="\n",
    )
